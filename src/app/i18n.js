let lang = 'es';
const listeners = new Set();

export function detectLang() {
  try {
    const saved = localStorage.getItem('b3d.lang');
    if (saved === 'es' || saved === 'en') return saved;
  } catch {
    /* sin storage */
  }
  return ((typeof navigator !== 'undefined' && navigator.language) || 'es').toLowerCase().startsWith('es') ? 'es' : 'en';
}

export function getLang() {
  return lang;
}

export function setLang(l) {
  lang = l === 'en' ? 'en' : 'es';
  try {
    localStorage.setItem('b3d.lang', lang);
  } catch {
    /* sin storage */
  }
  if (typeof document !== 'undefined') document.documentElement.lang = lang; // en Node (tests) no hay documento
  listeners.forEach((fn) => fn(lang));
}

export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function t(key, params = {}) {
  const s = dict[lang][key] ?? dict.es[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? ''));
}

/** Texto declarado como { es, en } (o string plano). */
export function tr(v) {
  if (v == null) return '';
  if (typeof v === 'string') return v;
  return v[lang] ?? v.es ?? '';
}

setLang(detectLang());
